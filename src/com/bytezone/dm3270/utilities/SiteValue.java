package com.bytezone.dm3270.utilities;

// Implementacao imutavel e headless de Site com acessores puros.
// toString() repete o formato de SiteForm em vez do padrao de record.
// -----------------------------------------------------------------------------------//
public record SiteValue (String name, String url, int port, boolean extended, int model,
    boolean plugins, boolean ssl, boolean trustAll, String folder) implements Site
// -----------------------------------------------------------------------------------//
{
  // ---------------------------------------------------------------------------------//
  @Override
  public String getName ()
  // ---------------------------------------------------------------------------------//
  {
    return name;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public String getURL ()
  // ---------------------------------------------------------------------------------//
  {
    return url;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public int getPort ()
  // ---------------------------------------------------------------------------------//
  {
    return port;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public boolean getExtended ()
  // ---------------------------------------------------------------------------------//
  {
    return extended;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public int getModel ()
  // ---------------------------------------------------------------------------------//
  {
    return model;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public boolean getPlugins ()
  // ---------------------------------------------------------------------------------//
  {
    return plugins;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public boolean getSsl ()
  // ---------------------------------------------------------------------------------//
  {
    return ssl;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public boolean getTrustAll ()
  // ---------------------------------------------------------------------------------//
  {
    return trustAll;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public String getFolder ()
  // ---------------------------------------------------------------------------------//
  {
    return folder;
  }

  // ---------------------------------------------------------------------------------//
  @Override
  public String toString ()
  // ---------------------------------------------------------------------------------//
  {
    return String.format ("Site [name=%s, url=%s, port=%d, folder=%s]", name, url, port,
        folder);
  }
}
